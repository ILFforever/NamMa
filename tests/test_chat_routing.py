def _run(conn, uid, msg, channel):
    if msg.startswith("@"):
        lat, lon = map(float, msg[1:].split(","))
        return chat.handle(conn, uid, channel, location=(lat, lon))
    return chat.handle(conn, uid, channel, text=msg)


